//! `cargo xtask gray16-table`: measures how GDI+ turns 16-bit grey PNG samples (no alpha) into
//! 8-bit values and writes the result as `crates/aurora-image/src/gdiplus_gray16_table.rs`.

use std::fmt::Write as _;
use std::path::{Path, PathBuf};

use anyhow::{Context, Result, ensure};

use crate::closeness_inputs::{RAMP_SIDE, write_gray16_ramp};
use crate::gdiplus_tool::{PowerShellHost, run_reference_tool};
use crate::golden::{Paths, absolute};

const TABLE_PATH: [&str; 4] = ["crates", "aurora-image", "src", "gdiplus_gray16_table.rs"];
const RAMP_REFERENCE: &str = "gray16_ramp.256x256.argb";
const BYTES_PER_PIXEL: usize = 4;
const VALUES_PER_LINE: usize = 12;

pub fn table_path(paths: &Paths) -> PathBuf {
    TABLE_PATH
        .iter()
        .fold(paths.root().to_path_buf(), |path, part| path.join(part))
}

/// The 8-bit grey GDI+ gives each 16-bit sample, read from the reference of the grey ramp.
fn gdiplus_grey_per_sample(argb: &[u8]) -> Result<Vec<u8>> {
    let pixels = argb.as_chunks::<BYTES_PER_PIXEL>().0;
    ensure!(
        pixels.len() == (RAMP_SIDE * RAMP_SIDE) as usize,
        "the grey ramp reference has {} pixels",
        pixels.len()
    );
    pixels
        .iter()
        .enumerate()
        .map(|(sample, &[alpha, red, green, blue])| {
            ensure!(
                alpha == u8::MAX && red == green && green == blue,
                "GDI+ turned grey sample {sample} into A,R,G,B {alpha},{red},{green},{blue}"
            );
            Ok(red)
        })
        .collect()
}

/// The first sample of each 8-bit value from 1 to 255; GDI+'s mapping must be monotonic and
/// reach every value, or no such table describes it.
fn thresholds(grey_per_sample: &[u8]) -> Result<Vec<u16>> {
    let mut thresholds = Vec::new();
    for (sample, pair) in grey_per_sample.windows(2).enumerate() {
        let (previous, next) = (pair[0], pair[1]);
        if next != previous {
            ensure!(
                next == previous + 1,
                "GDI+ jumps from {previous} to {next} at grey sample {}",
                sample + 1
            );
            thresholds.push((sample + 1) as u16);
        }
    }
    ensure!(
        grey_per_sample.first() == Some(&0) && thresholds.len() == usize::from(u8::MAX),
        "GDI+'s grey mapping does not cover 0 to 255"
    );
    Ok(thresholds)
}

fn table_source(thresholds: &[u16]) -> Result<String> {
    let mut source = String::new();
    writeln!(
        source,
        "//! Generated by `cargo xtask gray16-table` from GDI+ through\n//! tools/gdiplus/gdiplus-reference.ps1; do not edit.\n"
    )?;
    writeln!(
        source,
        "/// The first 16-bit grey sample (PNG, no alpha) that GDI+ turns into each 8-bit value from\n/// 1 to 255.\n#[rustfmt::skip]\npub(crate) const GDIPLUS_GRAY16_THRESHOLDS: [u16; {}] = [",
        thresholds.len()
    )?;
    for line in thresholds.chunks(VALUES_PER_LINE) {
        let values: Vec<String> = line.iter().map(u16::to_string).collect();
        writeln!(source, "    {},", values.join(", "))?;
    }
    writeln!(source, "];")?;
    Ok(source)
}

/// Runs GDI+ on the grey ramp in `work` and returns the table source it implies.
pub fn measure_table_source(paths: &Paths, work: &Path) -> Result<String> {
    let input_dir = work.join("gray16-inputs");
    let output_dir = work.join("gray16-gdiplus");
    std::fs::create_dir_all(&input_dir)?;
    write_gray16_ramp(&input_dir)?;
    let side = format!("{RAMP_SIDE}x{RAMP_SIDE}");
    run_reference_tool(
        paths,
        PowerShellHost::Bit32,
        &input_dir,
        &output_dir,
        Some(&side),
    )?;
    let reference = output_dir.join(RAMP_REFERENCE);
    let argb = std::fs::read(&reference)
        .with_context(|| format!("cannot read {}", reference.display()))?;
    table_source(&thresholds(&gdiplus_grey_per_sample(&argb)?)?)
}

pub fn write_table() -> Result<()> {
    ensure!(cfg!(windows), "the grey table needs Windows");
    let paths = Paths::new()?;
    let work_dir = tempfile::tempdir()?;
    let source = measure_table_source(&paths, &absolute(work_dir.path())?)?;
    let path = table_path(&paths);
    std::fs::write(&path, source).with_context(|| format!("cannot write {}", path.display()))?;
    println!("{}", path.display());
    Ok(())
}
